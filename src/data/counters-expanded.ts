const table: Record<string, string> = {
  じゅう: 'juu', にん: 'nin', いち: 'ichi', に: 'ni', さん: 'san', よ: 'yo', よん: 'yon', ご: 'go',
  ろく: 'roku', なな: 'nana', しち: 'shichi', はち: 'hachi', きゅう: 'kyuu', く: 'ku',
  にち: 'nichi', じ: 'ji', ふん: 'fun', ぷん: 'pun', まい: 'mai', ほん: 'hon', ぼん: 'bon',
  ぽん: 'pon', はい: 'hai', ぱい: 'pai', こ: 'ko', ひき: 'hiki', びき: 'biki', ぴき: 'piki',
  かい: 'kai', さい: 'sai', がつ: 'gatsu', じゅ: 'ju', きゅ: 'kyu', い: 'i', さ: 'sa',
  ろ: 'ro', な: 'na', は: 'ha', し: 'shi', ひ: 'hi', ふ: 'fu', び: 'bi', ぴ: 'pi',
  が: 'ga', つ: 'tsu', っ: '',
}
const keys = Object.keys(table).sort((a, b) => b.length - a.length)
function romanize(kana: string): string {
  let rest = kana
  let result = ''
  while (rest) {
    const key = keys.find((candidate) => rest.startsWith(candidate))
    if (!key) throw new Error(`Missing counter romanization for ${rest} in ${kana}`)
    if (key === 'っ') {
      const next = keys.find((candidate) => rest.slice(1).startsWith(candidate))
      if (!next) throw new Error(`Missing geminate target in ${kana}`)
      result += table[next][0]
    } else result += table[key]
    rest = rest.slice(key.length)
  }
  return result
}

export const COUNTER_EXPANSION_ROWS: Kana[][] = raw.map((row) =>
  row.map((item) => ({ ...item, romaji: romanize(item.kana) })),
)
